const WIDE: readonly (readonly [number, number])[] = [
  [0x1100, 0x115f],
  [0x2e80, 0xa4cf],
  [0xac00, 0xd7a3],
  [0xf900, 0xfaff],
  [0xfe30, 0xfe4f],
  [0xff00, 0xff60],
  [0xffe0, 0xffe6],
  [0x1f300, 0x1faff],
  [0x20000, 0x3fffd],
];

export class GlyphWidths {
  static readonly MONO = 0.602;
  static readonly OTHER = 0.72;
  private static readonly sans = GlyphWidths.table();

  static of(code: number, face: TextFace): number {
    if (code >= 0x300 && code <= 0x36f) return 0;
    if (WIDE.some(([from, to]) => code >= from && code <= to)) return 1;
    if (face === "mono") return GlyphWidths.MONO;
    return GlyphWidths.sans.get(code) ?? GlyphWidths.OTHER;
  }

  private static table(): Map<number, number> {
    const out = new Map<number, number>();
    for (const [first, row] of SANS_BOLD) {
      row.split(" ").forEach((value, k) => {
        if (value !== "0") out.set(first + k, Number(value) / 1000);
      });
    }
    return out;
  }
}
